package dev.rostisla.nyt.domain.model

/**
 * Причина, по которой новости не удалось загрузить.
 * UI по этому значению показывает пользователю конкретное объяснение вместо "что-то пошло не так".
 */
enum class StoriesError {
    /** Нет сети: хост не резолвится или соединение оборвалось. */
    NO_INTERNET,

    /** Сеть есть, но сервер не ответил за отведённое время. */
    TIMEOUT,

    /** Ключ NYT API не задан в local.properties — запрос даже не уходит. */
    API_KEY_MISSING,

    /** Сервер отклонил ключ: 401 / 403. */
    UNAUTHORIZED,

    /** Превышен лимит запросов к NYT API: 429. */
    RATE_LIMITED,

    /** Запрошенного раздела нет на сервере: 404. */
    NOT_FOUND,

    /** Ошибка на стороне NYT: 5xx. */
    SERVER,

    /** Ответ пришёл, но его не удалось разобрать. */
    BAD_RESPONSE,

    /** Ошибка локальной базы данных. */
    STORAGE,

    /** Запрос прошёл, но показывать нечего: ни в ответе, ни в кэше нет ни одной статьи. */
    NO_DATA,

    /** Всё остальное — подробности показываем текстом. */
    UNKNOWN
}
